const ICON_RE = new RegExp('(' + Object.keys(ICONS).sort((a, b) => b.length - a.length)
  .join('|') + ')️?', 'gu');
function iconSVG(e) {
  const d = ICONS[e]; if (!d) return '';
  const cls = d.c.split(' ').filter(Boolean);
  const fill = cls.includes('fill') ? 'currentColor' : 'none';
  return `<svg class="svg-ic ${d.c}" viewBox="0 0 24 24" fill="${fill}" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${d.p}</svg>`;
}
/* Sade tasarım: sadece anlam taşıyan simgeler her yerde çizilir; diğerleri yalnızca [data-icons] içinde (alet listesi gibi). */
const KEEP_ICONS = new Set(['⭐', '☆', '✅', '❌', '⚠', '⛔']);
const SKIP_ICON = 'svg,textarea,script,style,title,canvas,input';
function iconizeText(node) {
  const text = node.nodeValue;
  ICON_RE.lastIndex = 0;
  if (!ICON_RE.test(text)) return;
  const p = node.parentElement;
  if (!p || p.closest(SKIP_ICON)) return;
  ICON_RE.lastIndex = 0;
  const tpl = document.createElement('template');
  const keepAll = !!p.closest('[data-icons]');
  tpl.innerHTML = text.replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]))
    .replace(new RegExp(ICON_RE.source + ' ?', 'gu'), (m, e) => (keepAll || KEEP_ICONS.has(e) ? iconSVG(e) + (m.endsWith(' ') ? ' ' : '') : ''));
  node.replaceWith(tpl.content);
}
function iconize(root) {
  if (!root) return;
  if (root.nodeType === 3) { iconizeText(root); return; }
  if (root.nodeType !== 1 || root.closest(SKIP_ICON)) return;
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const list = [];
  while (w.nextNode()) list.push(w.currentNode);
  list.forEach(iconizeText);
}
new MutationObserver((muts) => {
  for (const m of muts) {
    if (m.type === 'characterData') iconize(m.target);
    else m.addedNodes.forEach(iconize);
  }
}).observe(document.documentElement, { childList: true, subtree: true, characterData: true });
